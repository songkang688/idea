#!/usr/bin/env python3
"""C-0306 killer-experiment prototype: conformal coverage vs NMS (SYNTHETIC).

Runs the full pipeline on synthetic scenes:
  [1] H1 blind-spot gate: fraction of GT objects whose covering candidates
      are ALL suppressed by standard NMS, across crowdedness x NMS threshold.
  [2] Conformal coverage before vs after NMS (pipelines A-D, see
      src/conformal_nms/pipelines.py).

Usage:
  python run_synthetic.py --config configs/default.yaml
  python run_synthetic.py --config configs/crowded_aggressive.yaml
  python run_synthetic.py --config configs/default.yaml --quick --json out.json

Every number printed is MEASURED ON SYNTHETIC DATA generated in-process.
Nothing here is a COCO/LVIS/CrowdHuman result and nothing should be quoted
as one. The EXPECTED lines restate exp_05's pre-registered hypotheses; the
MEASURED lines report what this synthetic run actually produced.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from dataclasses import asdict
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))

from conformal_nms import pipelines  # noqa: E402
from conformal_nms.blind_spot import blind_spot_table  # noqa: E402
from conformal_nms.config import load_config  # noqa: E402
from conformal_nms.synthetic import generate_dataset  # noqa: E402

DISCLAIMER = """\
================================================================================
 C-0306 prototype — conformal coverage vs NMS
 ALL NUMBERS BELOW ARE MEASURED ON SYNTHETIC DATA GENERATED BY THIS SCRIPT.
 They demonstrate the MECHANISM and the measurement/method machinery only.
 They are NOT results on COCO / LVIS / CrowdHuman or any real detector.
 The real killer experiment (exp_05) must measure the magnitude on cached
 pre-NMS candidates from real detectors before any claim is made.
================================================================================"""


def _fmt_pct(x: float) -> str:
    return f"{100.0 * x:6.2f}%"


def _fmt_qhat(q: float) -> str:
    return "  +inf" if math.isinf(q) else f"{q:6.3f}"


def run_level(level_name, crowd_cfg, cfg, seed):
    rng = np.random.default_rng(seed)
    scenes = generate_dataset(rng, cfg.n_scenes, crowd_cfg, cfg.detector)
    n_calib = int(round(cfg.calib_fraction * len(scenes)))
    calib, test = scenes[:n_calib], scenes[n_calib:]

    blind_rows = blind_spot_table(
        scenes, cfg.tau_iou, cfg.nms_iou_grid, cfg.nms_score_floor
    )

    results = [
        pipelines.run_keep_all(calib, test, cfg.alpha, cfg.tau_iou),
        pipelines.run_precalib_then_nms(
            calib, test, cfg.alpha, cfg.tau_iou, cfg.nms_deploy_iou,
            cfg.nms_score_floor,
        ),
        pipelines.run_conformal_after_nms(
            calib, test, cfg.alpha, cfg.tau_iou, cfg.nms_deploy_iou,
            cfg.nms_score_floor,
        ),
        pipelines.run_cps(
            calib, test, cfg.alpha, cfg.tau_iou, cfg.cps_kappa, cfg.cps_redundancy
        ),
    ]
    return blind_rows, results


def print_level(level_name, crowd_cfg, cfg, blind_rows, results):
    print(f"\n--- crowd level: {level_name} "
          f"(objects/scene ~ {crowd_cfg.objects_per_scene}, "
          f"cluster_fraction = {crowd_cfg.cluster_fraction}) ---")

    print(f"\n[1] Blind-spot gate (H1), tau = {cfg.tau_iou}, "
          f"n_gt = {blind_rows[0].n_gt}  [MEASURED, synthetic]")
    print("    nms_iou   miss(pre-NMS)   blind(uncond)   blind|detected")
    for r in blind_rows:
        print(f"    {r.nms_iou:7.2f}   {_fmt_pct(r.miss_rate):>13}   "
              f"{_fmt_pct(r.blind_rate):>13}   {_fmt_pct(r.blind_given_detected):>13}")

    print(f"\n[2] Conformal coverage, alpha = {cfg.alpha} "
          f"(nominal {1 - cfg.alpha:.2f}), deploy NMS iou = {cfg.nms_deploy_iou} "
          f"[MEASURED, synthetic]")
    header = (f"    {'pipeline':<38} {'coverage':>9} {'(SE)':>7} {'q_hat':>7} "
              f"{'cap':>6} {'set/scene':>9} {'dup/GT':>7} {'blind-cov':>9}")
    print(header)
    for r in results:
        blind_cov = (
            _fmt_pct(r.blind_stratum_coverage)
            if r.blind_stratum_coverage is not None
            else ("   n/a" if r.blind_stratum_n == 0 else "  0.00%")
        )
        print(f"    {r.name:<38} {_fmt_pct(r.coverage):>9} "
              f"({100 * r.coverage_se:4.2f}) {_fmt_qhat(r.qhat):>7} "
              f"{r.achievable_cap:6.3f} {r.mean_set_size:9.1f} "
              f"{r.duplicates_per_covered_gt:7.2f} {blind_cov:>9}")
    for r in results:
        if r.notes:
            print(f"      note [{r.name.split()[0]}]: {r.notes}")


def print_summary(cfg, all_levels):
    nominal = 1.0 - cfg.alpha
    level_names = list(all_levels)

    print("\n" + "=" * 80)
    print(" EXPECTED vs MEASURED (synthetic) — hypothesis checks from exp_05")
    print("=" * 80)

    # --- H1: blind spot grows with crowdedness and NMS aggressiveness ---
    print("\nH1 (blind-spot gate)")
    print("  EXPECTED (hypothesis, exp_05): a non-trivial fraction of GT objects")
    print("  lose ALL covering candidates to NMS; the fraction grows with scene")
    print("  crowdedness and with NMS aggressiveness (lower NMS IoU threshold).")
    deploy = cfg.nms_deploy_iou
    aggressive = min(cfg.nms_iou_grid)
    for probe_iou, label in ((aggressive, "most aggressive grid point"),
                             (deploy, "deploy operating point")):
        parts = []
        for name in level_names:
            rows = all_levels[name]["blind_rows"]
            row = next(r for r in rows if r.nms_iou == probe_iou)
            parts.append(f"{name} = {100 * row.blind_rate:.2f}%")
        print(f"  MEASURED (synthetic): blind rate @ NMS iou {probe_iou} "
              f"({label}): " + ", ".join(parts))
    last = all_levels[level_names[-1]]["blind_rows"]
    trend = ", ".join(
        f"iou {r.nms_iou:.2f} -> {100 * r.blind_rate:.2f}%" for r in last
    )
    print(f"  MEASURED (synthetic): blind rate vs NMS threshold "
          f"({level_names[-1]}): {trend}")
    rates = [
        next(
            r for r in all_levels[n]["blind_rows"] if r.nms_iou == aggressive
        ).blind_rate
        for n in level_names
    ]
    verdict = "consistent" if all(
        rates[i] <= rates[i + 1] + 1e-9 for i in range(len(rates) - 1)
    ) else "NOT monotone across levels"
    print(f"  VERDICT on this synthetic: {verdict} with H1 at NMS iou "
          f"{aggressive} (config lists levels sparse -> crowded).")

    # --- Coverage claim: post-NMS coverage != nominal for the pre-NMS guarantee ---
    print("\nCoverage destruction (the falsifiable claim)")
    print("  EXPECTED (hypothesis): a split-conformal guarantee calibrated pre-NMS")
    print("  no longer holds at the nominal level after standard NMS; the gap")
    print("  tracks the blind-spot rate. On blind objects coverage is 0 by")
    print("  construction — no threshold can recover them.")
    for name in level_names:
        res = all_levels[name]["results"]
        a, b, c, d = res
        gap = nominal - b.coverage
        z = gap / max(b.coverage_se, 1e-12)
        print(f"  MEASURED ({name}, synthetic): pre-NMS coverage "
              f"{100 * a.coverage:.2f}% vs nominal {100 * nominal:.0f}%; "
              f"post-NMS (pipeline B) {100 * b.coverage:.2f}% "
              f"(gap {100 * gap:+.2f} pp, z = {z:.1f})")
        if math.isinf(c.qhat):
            print(f"  MEASURED ({name}, synthetic): calibrate-AFTER-NMS returns "
                  f"q_hat = +inf — nominal {100 * nominal:.0f}% is UNACHIEVABLE "
                  f"post-NMS (achievable cap {100 * c.achievable_cap:.2f}%); "
                  f"measured coverage {100 * c.coverage:.2f}%")
        else:
            print(f"  MEASURED ({name}, synthetic): calibrate-AFTER-NMS restores "
                  f"marginal coverage to {100 * c.coverage:.2f}% "
                  f"(blind stratum stays at "
                  f"{0.0 if c.blind_stratum_coverage is None else 100 * c.blind_stratum_coverage:.1f}%"
                  f" on n = {c.blind_stratum_n})")

    # --- CPS: the constructive leg ---
    print("\nCoverage-preserving suppression (constructive sketch, H2 direction)")
    print("  EXPECTED (by the CPS theorem, suppression.py): coverage >= nominal")
    print("  within sampling error, with sets far smaller than keep-all.")
    for name in level_names:
        a, b, c, d = all_levels[name]["results"]
        ratio = d.mean_set_size / max(a.mean_set_size, 1e-9)
        print(f"  MEASURED ({name}, synthetic): CPS coverage "
              f"{100 * d.coverage:.2f}% (nominal {100 * nominal:.0f}%), "
              f"set size {d.mean_set_size:.1f}/scene = {100 * ratio:.0f}% of "
              f"keep-all ({a.mean_set_size:.1f}), duplicates/GT "
              f"{d.duplicates_per_covered_gt:.2f} vs keep-all "
              f"{a.duplicates_per_covered_gt:.2f}")

    print("\nREMINDER: synthetic mechanism demo. The magnitude on real data is the")
    print("open question exp_05's killer experiment exists to measure.")


def to_json(cfg, all_levels) -> dict:
    out = {
        "disclaimer": "SYNTHETIC data only; not COCO/LVIS/CrowdHuman results",
        "alpha": cfg.alpha,
        "tau_iou": cfg.tau_iou,
        "nms_deploy_iou": cfg.nms_deploy_iou,
        "levels": {},
    }
    for name, blob in all_levels.items():
        out["levels"][name] = {
            "blind_spot": [asdict(r) for r in blob["blind_rows"]],
            "pipelines": [asdict(r) for r in blob["results"]],
        }
    return out


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default="configs/default.yaml",
                        help="YAML config path")
    parser.add_argument("--seed", type=int, default=None,
                        help="override config seed")
    parser.add_argument("--quick", action="store_true",
                        help="cap scenes per level at 80 (smoke run)")
    parser.add_argument("--json", default=None, metavar="PATH",
                        help="also dump results as JSON")
    args = parser.parse_args(argv)

    cfg = load_config(args.config)
    if args.seed is not None:
        cfg.seed = args.seed
    if args.quick:
        cfg.n_scenes = min(cfg.n_scenes, 80)

    print(DISCLAIMER)
    print(f"\nconfig: {args.config}  seed: {cfg.seed}  "
          f"scenes/level: {cfg.n_scenes}  alpha: {cfg.alpha}  tau: {cfg.tau_iou}")

    seed_seq = np.random.SeedSequence(cfg.seed)
    child_seeds = seed_seq.spawn(len(cfg.crowd_levels))

    all_levels = {}
    for (name, crowd_cfg), child in zip(cfg.crowd_levels.items(), child_seeds):
        blind_rows, results = run_level(name, crowd_cfg, cfg, child)
        all_levels[name] = {"blind_rows": blind_rows, "results": results}
        print_level(name, crowd_cfg, cfg, blind_rows, results)

    print_summary(cfg, all_levels)

    if args.json:
        Path(args.json).write_text(json.dumps(to_json(cfg, all_levels), indent=2))
        print(f"\nwrote JSON results to {args.json}")

    return all_levels


if __name__ == "__main__":
    main()
